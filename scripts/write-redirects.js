/**
 * Runs after `expo export` and writes dist/_redirects (Netlify's routing rules)
 * plus dist/404.html.
 *
 * Why this is needed: Expo exports a page with a changing part of the address,
 * such as /profile/<id> or /s/<token>, as a single file named "[id].html" or
 * "[token].html". Netlify does not know that on its own, so opening such a
 * link directly (from Facebook, a text message, or a browser refresh) showed
 * Netlify's own "Page not found". The rules below tell Netlify which file to
 * serve for each of those addresses. They are generated from the exported
 * files, so a new dynamic page needs no change here.
 *
 * Share links (/s/<token>) are instead forwarded to the Supabase function
 * `share-preview`, which gives Facebook, iMessage and friends a proper
 * preview card and sends people on to the normal page. The Supabase project
 * address comes from EXPO_PUBLIC_SUPABASE_URL (already set in Netlify), so
 * nothing is hard-coded here. Without that variable the share page is served
 * directly, like every other page.
 */
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'dist');
if (!fs.existsSync(dist)) {
  console.log('write-redirects: no dist folder, nothing to do.');
  process.exit(0);
}

// Supabase address for the share-preview forwarding rule (optional).
const raw = (process.env.EXPO_PUBLIC_SUPABASE_URL || '').trim().replace(/^["']|["']$/g, '');
let supabaseOrigin = '';
try {
  supabaseOrigin = new URL(raw).origin;
} catch {
  supabaseOrigin = '';
}

// Find every "[something].html" in the export, skipping Expo's internal
// folders and the "(group)" copies that Expo also writes.
const dynamicPages = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('_expo') || entry.name.startsWith('(')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/^\[[^\]]+\]\.html$/.test(entry.name)) dynamicPages.push(path.relative(dist, full));
  }
};
walk(dist);

const lines = [
  '# Generated by scripts/write-redirects.js at build time. Do not edit by hand.',
  '# First matching rule wins.',
];

if (supabaseOrigin) {
  lines.push('# Share links get rich previews from the share-preview function (docs/SHARE_PREVIEWS.md).');
  lines.push(`/s/*  ${supabaseOrigin}/functions/v1/share-preview/:splat  200`);
} else {
  console.log('write-redirects: EXPO_PUBLIC_SUPABASE_URL is not set, share links will use the plain page.');
}

lines.push('# Pages with a changing part in the address, e.g. /profile/<id> -> profile/[id].html.');
// Deeper folders first so /admin/member/* is matched before any shorter rule.
dynamicPages
  .map((p) => p.split(path.sep).join('/'))
  .sort((a, b) => b.split('/').length - a.split('/').length || a.localeCompare(b))
  .forEach((page) => {
    const folder = path.posix.dirname(page);
    lines.push(`/${folder}/*  /${page}  200`);
  });
lines.push('');
fs.writeFileSync(path.join(dist, '_redirects'), lines.join('\n'));

// Netlify shows dist/404.html for addresses that match nothing above.
const notFound = path.join(dist, '+not-found.html');
if (fs.existsSync(notFound)) fs.copyFileSync(notFound, path.join(dist, '404.html'));

console.log(`write-redirects: wrote dist/_redirects with ${dynamicPages.length} dynamic page rule(s)${supabaseOrigin ? ' and the share-preview rule' : ''}.`);
