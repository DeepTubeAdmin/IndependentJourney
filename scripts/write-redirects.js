/**
 * Runs after `expo export` and writes dist/_redirects for Netlify.
 *
 * Share links (/s/<token>) are forwarded to the Supabase function
 * `share-preview`, which gives Facebook, iMessage and friends a proper
 * preview card and sends people on to the normal page. The Supabase project
 * address comes from EXPO_PUBLIC_SUPABASE_URL (already set in Netlify), so
 * nothing is hard-coded here.
 */
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'dist');
const raw = (process.env.EXPO_PUBLIC_SUPABASE_URL || '').trim().replace(/^["']|["']$/g, '');
let origin = '';
try {
  origin = new URL(raw).origin;
} catch {
  origin = '';
}

if (!fs.existsSync(dist)) {
  console.log('write-redirects: no dist folder, nothing to do.');
  process.exit(0);
}
if (!origin) {
  console.log('write-redirects: EXPO_PUBLIC_SUPABASE_URL is not set, share links will use the plain page.');
  process.exit(0);
}

const lines = [
  '# Generated by scripts/write-redirects.js at build time. Do not edit by hand.',
  '# Share links get rich previews from the share-preview function (docs/SHARE_PREVIEWS.md).',
  `/s/*  ${origin}/functions/v1/share-preview/:splat  200`,
  '',
];
fs.writeFileSync(path.join(dist, '_redirects'), lines.join('\n'));
console.log('write-redirects: wrote dist/_redirects for share previews.');
